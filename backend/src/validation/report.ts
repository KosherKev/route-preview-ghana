export interface RealRow {
  routeId: string;
  label: string;
  costing: Costing;
  origin: LatLon;
  destination: LatLon;
  status: "ok" | "error";
  error?: string;
  routeLengthKm?: number;
  approachLengthM?: number;
  approachWholeRoute?: boolean;
  approachEdgeCount?: number;
  routeEdgeCount?: number;
  unpaved_fallback?: boolean;
  decisionWindowCount?: number;
  named?: Record<NamedKey, { distanceM: number; relation: "ends_at" | "through" | "no" }>;
  classification?: {
    modes: string[];
    usableFrames: number;
    candidateFrames: number;
    framesPer100m: number;
    maxGapM: number | null;
    streetFraction: number;
    levelUncertainSegments: number;
    segmentCount: number;
  };
}

export interface ValidationReport {
  generatedAt: string;
  /** Why this branch is not merged (see NOT_MERGED_NOTICE). */
  branchStatus: string;
  /** Always false in Phase 3. */
  liveImageryMeasured: false;
  mapillaryTokenConfigured: boolean;
  statement: string;
  frameRowsInDatabase: number;
  config: { match: typeof DEFAULT_MATCH_CONFIG; classify: typeof DEFAULT_CLASSIFY_CONFIG; approachLengthM: number; decisionWindowM: number };
  namedPoints: Record<NamedKey, { name: string; at: LatLon }>;
  realRoutes: RealRow[];
  synthetic: {
    synthetic: true;
    label: string;
    scenarios: SyntheticScenario[];
  };
}

export const SYNTHETIC_LABEL =
  "SYNTHETIC: artificial frames generated by the test fixture builder to demonstrate classifier outcomes. This is not real imagery and not a coverage measurement.";

export function summariseClassification(p: PipelineResult) {
  const c: Classification = p.classification;
  return {
    modes: [...new Set(c.segments.map((s) => s.mode))],
    usableFrames: p.usableFrames,
    candidateFrames: p.candidateFrames,
    framesPer100m: c.summary.framesPer100m,
    maxGapM: c.summary.maxGapM,
    streetFraction: c.summary.streetFraction,
    levelUncertainSegments: c.summary.levelUncertainSegments,
    segmentCount: c.segments.length,
  };
}

const f1 = (n: number | null | undefined) => (n === null || n === undefined ? "n/a" : n.toFixed(1));
const f3 = (n: number | null | undefined) => (n === null || n === undefined ? "n/a" : n.toFixed(3));
const ll = (p: LatLon) => `${p.lat.toFixed(5)}, ${p.lon.toFixed(5)}`;

export function renderMarkdown(r: ValidationReport): string {
  const L: string[] = [];
  L.push("# Route preview validation (Phase 3)", "");
  L.push(`Generated: ${r.generatedAt}`, "");
  L.push("## Branch status", "", `**${r.branchStatus}**`, "");
  L.push("## Statement: live imagery was NOT measured", "");
  L.push(`**${r.statement}**`, "");
  L.push(`- Mapillary token configured: ${r.mapillaryTokenConfigured ? "yes (never used by this tool)" : "no"}`);
  L.push(`- Rows in the \`frames\` table at run time: ${r.frameRowsInDatabase}`, "");
  L.push("What the real-route section DOES verify: Valhalla routing, approach extraction (about 500 m along the route), edge ids, the `unpaved_fallback` handling, and that the classifier degrades safely to BIRDS_EYE_3D when there is no imagery.", "");
  L.push("## Thresholds used", "");
  L.push(`- Approach length ${r.config.approachLengthM} m along the route; decision windows ${r.config.decisionWindowM} m.`);
  L.push(`- Street run: at least ${r.config.classify.minRunM} m long and every gap between consecutive usable frames strictly under ${r.config.classify.maxGapM} m (maximum, not average).`);
  L.push(`- Two-tier gap rule (confirmed by the owner 2026-11-20): gap under ${r.config.classify.maxGapM} m is RIFE-eligible (AI interpolation is allowed ONLY below this ceiling); ${r.config.classify.maxGapM} m to ${r.config.classify.crossfadeMaxGapM} m, both ends inclusive, between two qualifying runs is a crossfade bridge that merges them into ONE STREET_VIDEO segment and is NEVER RIFE-interpolated; a gap over ${r.config.classify.crossfadeMaxGapM} m, or a run under ${r.config.classify.minRunM} m that cannot be bridged, hands off to BIRDS_EYE_3D.`);
  L.push(`- The rule is applied pairwise: a chain of qualifying runs each joined by a ${r.config.classify.maxGapM}-${r.config.classify.crossfadeMaxGapM} m gap is one segment with several bridges.`);
  L.push(`- Frame filters: lateral tolerance ${r.config.match.lateralToleranceM} m, more than ${r.config.match.maxLeftOffsetM} m left of the centreline dropped (right-hand traffic), heading within +/-${r.config.match.bearingToleranceDeg} deg of the local road bearing, quality_score at least ${r.config.match.minQualityScore}.`);
  L.push(`- level_uncertain: sequence jump, heading jump over ${r.config.classify.headingJumpDeg} deg, or road class/use/bridge/tunnel/layer change at an edge transition, padded ${r.config.classify.levelPadM} m each side.`, "");
  L.push("## Named places (coordinates used)", "");
  L.push("| Place | lat, lon | How located |", "| --- | --- | --- |");
  const how: Record<NamedKey, string> = {
    kwameNkrumahInterchange: "Not in landmarks by name; located from Valhalla roundabout maneuvers named \"Kwame Nkrumah Circle\" (5.5693-5.5698, -0.2157 to -0.2150)",
    tettehQuarshieInterchange: "landmarks row, osm node 493773904, motorway_junction \"Tetteh Quarshie Interchange\"",
    danquahCircle: "Valhalla roundabout maneuvers named \"Danquah Circle\" (5.5669-5.5670, -0.1812 to -0.1806)",
  };
  for (const k of Object.keys(r.namedPoints) as NamedKey[]) L.push(`| ${r.namedPoints[k].name} | ${ll(r.namedPoints[k].at)} | ${how[k]} |`);
  L.push("", `A route is marked "through" a named place if it passes within ${NEAR_NAMED_M} m of it, or "ends at" if that closest point is within ${NEAR_NAMED_M} m of the route's start or end.`, "");

  L.push("## Real routes (live Valhalla, PostGIS frames table)", "");
  L.push("Each pair is run with both costings. Approach length, edge counts, classifier columns and frame counts describe the final approach (the last ~500 m along the route); the Named places column and Route km describe the whole route. A row with \"no route\" is a genuine routing failure reported as is.", "");
  L.push("| Route | Costing | Origin | Destination | Route km | Approach m | Edges (approach / route) | unpaved_fallback | Named places | Classifier | Frames used | Frames/100 m | Max gap m | level_uncertain |");
  L.push("| --- | --- | --- | --- | ---: | ---: | --- | --- | --- | --- | ---: | ---: | ---: | ---: |");
  for (const x of r.realRoutes) {
    if (x.status === "error" || !x.classification) {
      L.push(`| ${x.routeId} ${x.label} | ${x.costing} | ${ll(x.origin)} | ${ll(x.destination)} | no route | | | | | error: ${x.error ?? "unknown"} | | | | |`);
      continue;
    }
    const named = x.named ? (Object.keys(x.named) as NamedKey[]).filter((k) => x.named![k].relation !== "no").map((k) => `${NAMED_POINTS[k].name.split(" (")[0]} (${x.named![k].relation === "ends_at" ? "ends at" : "through"}, ${x.named![k].distanceM} m)`).join("; ") : "";
    const c = x.classification;
    L.push(`| ${x.routeId} ${x.label} | ${x.costing} | ${ll(x.origin)} | ${ll(x.destination)} | ${f1(x.routeLengthKm)} | ${f1(x.approachLengthM)}${x.approachWholeRoute ? " (whole route)" : ""} | ${x.approachEdgeCount} / ${x.routeEdgeCount} | ${x.unpaved_fallback ? "TRUE" : "false"} | ${named || "none"} | ${c.modes.join(", ")} | ${c.usableFrames} | ${f1(c.framesPer100m)} | ${f1(c.maxGapM)} | ${c.levelUncertainSegments} |`);
  }
  const ok = r.realRoutes.filter((x) => x.status === "ok");
  L.push("", `Routes attempted: ${r.realRoutes.length}; routed: ${ok.length}; no route/error: ${r.realRoutes.length - ok.length}; unpaved_fallback used: ${ok.filter((x) => x.unpaved_fallback).length}; classified STREET_VIDEO anywhere: ${ok.filter((x) => x.classification?.modes.includes("STREET_VIDEO")).length}.`, "");

  L.push("## SYNTHETIC classifier demonstrations", "");
  L.push(`**${r.synthetic.label}**`, "");
  L.push("Everything in this section is SYNTHETIC. Nothing here says anything about real roads or real imagery coverage.", "");
  for (const s of r.synthetic.scenarios) {
    L.push(`### SYNTHETIC: ${s.title}`, "", s.description, "", `Expected: ${s.expectation}`, "");
    L.push(`Route ${f1(s.routeLengthM)} m, ${s.frameCount} synthetic frames, ${s.result.usableFrames} usable after filtering; dropped: ${JSON.stringify(s.result.dropped)}.`, "");
    L.push("| Segment | Mode | From m | To m | Frames | Max gap m | level_uncertain | Bridges (crossfade, not RIFE) | Reason |", "| --- | --- | ---: | ---: | ---: | ---: | --- | --- | --- |");
    s.result.classification.segments.forEach((g, i) => {
      L.push(`| ${i + 1} | ${g.mode} | ${f1(g.startM)} | ${f1(g.endM)} | ${g.frameCount} | ${f3(g.maxGapM)} | ${g.level_uncertain ? g.level_uncertain_reasons.join("+") : "no"} | ${g.bridges.map((c) => `${f1(c.startM)}-${f1(c.endM)} (${f3(c.gapM)} m)`).join(", ") || "none"} | ${g.birdsEyeReason ?? "street run"} |`);
    });
    L.push("");
  }
  return L.join("\n") + "\n";
}
