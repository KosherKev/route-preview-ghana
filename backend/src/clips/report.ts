// Phase 4 per-clip report: numbers and metadata only, built from the gitignored clip result files, their plans, the download
// budget file and the cache directories. No imagery, thumbnail or clip is read or written.
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import path from "node:path";
import type { ClipPlan } from "./plan";
import type { ClipResult } from "./register";

export const MAX_DOWNLOADS = 1000; // the worker's hard cap (worker/rpg_worker/budget.py)

export interface ClipReportRow {
  edge_id: number; direction: string; duration_s: number; fps: number; nominal_speed_mps: number; frame_count: number;
  source_frames: number; interpolated_frames: number; bridge_frames: number;
  /** interpolated / (source + interpolated + bridge): the share of distinct keyframes that were synthesised by minterpolate. */
  interpolated_share: number;
  bridges_used: number; interpolator: string; file_bytes: number; encode_seconds: number;
  capture_year_buckets: Record<string, number>;
}
export interface ClipReport {
  clips: ClipReportRow[];
  totals: {
    clips: number; total_duration_s: number; total_bridges_used: number; total_interpolated_frames: number;
    mapillary_downloads: number; mapillary_downloads_cap: number; mapillary_api_calls: number;
    frames_cache_bytes: number; clips_cache_bytes: number;
  };
}

export function dirBytes(dir: string): number {
  if (!existsSync(dir)) return 0;
  let n = 0;
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    n += e.isDirectory() ? dirBytes(p) : statSync(p).size;
  }
  return n;
}

const round = (x: number, d = 3) => Math.round(x * 10 ** d) / 10 ** d;

export function buildClipReport(dirs: { results: string; plans: string; budgetFile: string; framesCache: string; clipsCache: string }): ClipReport {
  const clips = readdirSync(dirs.results).filter((n) => n.endsWith(".json")).sort().map((f): ClipReportRow => {
    const r = JSON.parse(readFileSync(path.join(dirs.results, f), "utf8")) as ClipResult;
    const planFile = path.join(dirs.plans, f);
    const buckets: Record<string, number> = {};
    if (existsSync(planFile)) {
      const plan = (JSON.parse(readFileSync(planFile, "utf8")) as { plan: ClipPlan }).plan;
      for (const fr of plan.frames) {
        const t = (fr as { captured_at?: string | null }).captured_at;
        const y = t ? String(new Date(t).getUTCFullYear()) : "unknown";
        buckets[y] = (buckets[y] ?? 0) + 1;
      }
    }
    const keyframes = r.source_frames + r.interpolated_frames + r.bridge_frames;
    return {
      edge_id: r.edge_id, direction: r.direction, duration_s: r.duration_s, fps: r.fps, nominal_speed_mps: r.speed_mps, frame_count: r.frame_count,
      source_frames: r.source_frames, interpolated_frames: r.interpolated_frames, bridge_frames: r.bridge_frames,
      interpolated_share: keyframes ? round(r.interpolated_frames / keyframes) : 0,
      bridges_used: r.bridges_used, interpolator: r.interpolator, file_bytes: r.file_bytes, encode_seconds: r.encode_seconds,
      capture_year_buckets: Object.fromEntries(Object.entries(buckets).sort()),
    };
  });
  const budget = JSON.parse(readFileSync(dirs.budgetFile, "utf8")) as { downloads: number; api_calls: number };
  return {
    clips,
    totals: {
      clips: clips.length, total_duration_s: round(clips.reduce((s, c) => s + c.duration_s, 0)),
      total_bridges_used: clips.reduce((s, c) => s + c.bridges_used, 0), total_interpolated_frames: clips.reduce((s, c) => s + c.interpolated_frames, 0),
      mapillary_downloads: budget.downloads, mapillary_downloads_cap: MAX_DOWNLOADS, mapillary_api_calls: budget.api_calls,
      frames_cache_bytes: dirBytes(dirs.framesCache), clips_cache_bytes: dirBytes(dirs.clipsCache),
    },
  };
}

const mb = (b: number) => `${(b / 1_048_576).toFixed(2)} MB`;

export function renderClipReportMarkdown(r: ClipReport): string {
  const t = r.totals;
  const L: string[] = [
    "# Phase 4 prototype clips report", "",
    "Generated by `npm run clips:report` (backend) from the gitignored clip result files, `data/mapillary-budget.json` and the cache directories. " +
      "Numbers and metadata only: no imagery, thumbnails, contact sheets or clips are committed. Every clip is a PROTOTYPE (status `prototype`), never served or uploaded.", "",
    "## Totals", "",
    `- Clips: ${t.clips}; total duration ${t.total_duration_s} s`,
    `- Mapillary image downloads: ${t.mapillary_downloads} of ${t.mapillary_downloads_cap}; Mapillary API calls: ${t.mapillary_api_calls}`,
    `- Frames cache on disk: ${t.frames_cache_bytes} bytes (${mb(t.frames_cache_bytes)}); clips cache on disk: ${t.clips_cache_bytes} bytes (${mb(t.clips_cache_bytes)})`,
    `- Bridges used across all clips: ${t.total_bridges_used}; interpolated frames across all clips: ${t.total_interpolated_frames}`, "",
    "## Per clip", "",
    "Interpolated share = interpolated / (source + interpolated + bridge) keyframes. Frame count is output frames at the constant frame rate (each keyframe is held for the metres it covers).", "",
    "| Edge id | Dir | Duration s | fps | Speed m/s | Frames | Source | Interpolated | Share | Bridge | Bridges used | Interpolator | File bytes | Encode s | Capture years (source frames) |",
    "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
  ];
  for (const c of r.clips) {
    const yrs = Object.entries(c.capture_year_buckets).map(([y, n]) => `${y}: ${n}`).join(", ") || "n/a";
    L.push(`| ${c.edge_id} | ${c.direction} | ${c.duration_s} | ${c.fps} | ${c.nominal_speed_mps} | ${c.frame_count} | ${c.source_frames} | ${c.interpolated_frames} | ` +
      `${(c.interpolated_share * 100).toFixed(1)}% | ${c.bridge_frames} | ${c.bridges_used} | ${c.interpolator} | ${c.file_bytes} | ${c.encode_seconds} | ${yrs} |`);
  }
  L.push("", "## Limits", "",
    `- Only ${t.clips} prototype clips exist; this is not a sample of the network.`,
    `- ${t.total_bridges_used === 1 ? "One real bridge" : `${t.total_bridges_used} real bridge(s)`} (a 15 to 30 m crossfade) occurs across all of them, so the bridge path has barely been exercised on real imagery.`,
    "- minterpolate smears and doubles billboards, buildings and vehicles whose apparent position shifts a lot between frames; judged on about nine hand-picked frames, not exhaustively.",
    "- RIFE was skipped: the upstream release publishes no checksum, so the verified-binary rule cannot be met, and Vulkan through MoltenVK on this Intel Iris Pro is doubtful.",
    "- Real ffprobe has not been run on these clips (none is installed); the ffmpeg stream parse and the MP4 box walk were used instead.", "");
  return L.join("\n");
}
